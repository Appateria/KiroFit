def gen_adoption() -> None:
    rows = []
    for d in days():
        mau = mau_curve(d)
        dau = int(mau * 0.34 * weekend_factor(d) * rng.uniform(0.95, 1.05))
        t = (d - WINDOW_START).days
        for key, route, tier, share, trend in FEATURES:
            s = max(0.005, share + trend * t) * rng.uniform(0.93, 1.07)
            users = int(dau * s)
            sessions = int(users * rng.uniform(1.1, 1.9))
            rows.append([d.isoformat(), key, route, tier, dau, users,
                         round(users / dau * 100, 2), sessions])
    write_csv(
        "04-usage-behavioral/feature-adoption-daily.csv",
        ["date", "feature_key", "route", "min_tier", "dau_total", "feature_dau",
         "feature_dau_pct_of_dau", "feature_sessions"],
        rows,
    )


