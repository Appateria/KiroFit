def gen_event_sample(n: int = 2400) -> None:
    names = [e for e, _ in EVENT_MIX]
    weights = [w for _, w in EVENT_MIX]
    tiers = ["guest"] * 46 + ["free"] * 47 + ["premium"] * 7
    platforms = ["ios_web"] * 44 + ["android_web"] * 33 + ["desktop_web"] * 23
    records = []
    for i in range(n):
        d = WINDOW_START + timedelta(days=rng.randint(100, 147))
        ts = datetime(d.year, d.month, d.day, rng.randint(5, 23),
                      rng.randint(0, 59), rng.randint(0, 59), tzinfo=timezone.utc)
        name = rng.choices(names, weights)[0]
        tier = rng.choice(tiers)
        rec = {
            "event_id": f"evt_{SEED}_{i:05d}",
            "event": name,
            "ts": ts.isoformat().replace("+00:00", "Z"),
            "anonymous_id": f"anon_{rng.randint(10000, 99999)}",
            "user_id": None if tier == "guest" else f"usr_{rng.randint(1000, 9999)}",
            "tier": tier,
            "platform": rng.choice(platforms),
            "app_version": "1.0.0",
            "route": EVENT_ROUTE.get(name, "/tabs/exercise"),
            "props": {},
        }
        if name == "exercise_entry_saved":
            rec["props"] = {"activity_type": rng.choice(["running", "walking", "cycling",
                                                         "strength", "yoga", "swimming"]),
                            "duration_minutes": rng.randrange(15, 95, 5),
                            "weight_units_shown": "kg", "distance_units_shown": "km"}
        elif name == "repeat_previous_session":
            rec["props"] = {"identical_to_previous": True,
                            "consecutive_repeats": rng.randint(2, 9),
                            "plan_source": None}
        elif name == "history_range_change_attempted":
            rec["props"] = {"requested_range": rng.choice(["week", "month", "90d", "custom"]),
                            "succeeded": False,
                            "reason": "exerciseEntries requires a single AWSDate"}
        elif name == "report_export_attempted":
            rec["props"] = {"requested_period": rng.choice(["1w", "1m"]),
                            "succeeded": False, "reason": "no report capability"}
        elif name == "profile_unit_confusion":
            rec["props"] = {"field": rng.choice(["weightKg", "heightCm"]),
                            "entered_value": rng.choice([165, 180, 5.9, 6.1, 154, 210]),
                            "plausible_unit": rng.choice(["lb", "in", "ft"]),
                            "stored_unit": rng.choice(["kg", "cm"])}
        elif name == "guest_sync_partial_failure":
            total = rng.randint(3, 12)
            rec["props"] = {"entries_total": total, "entries_synced": rng.randint(0, total - 1),
                            "local_cache_cleared": True}
        elif name == "upgrade_placeholder_toast_shown":
            rec["props"] = {"message": "Premium subscriptions will be available soon."}
        elif name == "photo_upload_failed":
            rec["props"] = {"content_type": "image/heic", "status": 403,
                            "reason": "content_type_not_allowed"}
        elif name == "history_opened":
            rec["props"] = {"range": "week", "queries_issued": 7,
                            "render_ms": rng.randint(2100, 9600)}
        elif name == "upgrade_tapped":
            rec["props"] = {"surface": "subscription_page"}
        records.append(rec)
    records.sort(key=lambda r: r["ts"])
    write_jsonl("04-usage-behavioral/product-events-sample.jsonl", records)


