#!/usr/bin/env python3
"""
Deterministic generator for the volumetric (time-series / event-level) parts of the
Kiro Fit Product Signal Repository synthetic dataset.

Qualitative artifacts (interviews, analyst notes, OKRs, opportunity briefs) are
authored by hand. Everything this script emits is derived from a fixed seed so the
committed CSV/TSV/JSONL files can be regenerated byte-identically:

    python3 signal-data/tools/generate_timeseries.py

Narrative baked into the numbers (so the six signal classes corroborate each other):

  * 2026-04-01 .. 2026-08-26 observation window (148 days), "today" = 2026-08-27.
  * 2026-06-18 release r-1.0.14 makes guest-sync failures worse (error-rate step).
  * exerciseEntries p99 degrades steadily as history volume grows (per-day N+1 fan-out).
  * Adoption of logging decays; guest -> free conversion stalls at the sign-up prompt;
    subscription page converts to nothing (placeholder toast).
  * Help-centre search is dominated by three capabilities the product does not have:
    a generated workout plan, a periodic progress report, and imperial units.
  * Exercise history range changes convert to zero (no range query, no report).

Calorie-consumption tracking was removed from ../src, so no operation, feature,
funnel, cohort or event in this generator references food logging. Signals about a
feature that no longer exists are noise.
"""

from __future__ import annotations

import csv
import json
import math
import random
from datetime import date, datetime, timedelta, timezone
from pathlib import Path

SEED = 20260827
ROOT = Path(__file__).resolve().parents[1]
WINDOW_START = date(2026, 4, 1)
WINDOW_END = date(2026, 8, 26)
GUEST_SYNC_REGRESSION = date(2026, 6, 18)

rng = random.Random(SEED)


def days(start: date = WINDOW_START, end: date = WINDOW_END):
    d = start
    while d <= end:
        yield d
        d += timedelta(days=1)


def write_csv(relpath: str, header: list[str], rows: list[list], delimiter: str = ",") -> None:
    path = ROOT / relpath
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, delimiter=delimiter, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    print(f"wrote {relpath} ({len(rows)} rows)")


def write_jsonl(relpath: str, records: list[dict]) -> None:
    path = ROOT / relpath
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        for rec in records:
            fh.write(json.dumps(rec, separators=(",", ":")) + "\n")
    print(f"wrote {relpath} ({len(records)} records)")


def weekend_factor(d: date) -> float:
    return 0.78 if d.weekday() >= 5 else 1.0


def mau_curve(d: date) -> int:
    """Installed base grows, active base flattens then dips as churn bites."""
    t = (d - WINDOW_START).days
    growth = 4200 + 62 * t - 0.19 * t * t
    return int(max(3200, growth) * weekend_factor(d) / 0.94)


# ---------------------------------------------------------------------------
# 02 — defect & degradation: AppSync resolver error rates
# ---------------------------------------------------------------------------

OPERATIONS = [
    # name,               kind,       base_rpd, base_err_pct, note
    ("Query.exerciseEntries", "query", 1.12, 0.51, "per-date fan-out"),
    ("Query.healthProfile", "query", 0.46, 0.31, "read path"),
    ("Query.me", "query", 0.52, 0.22, "read path"),
    ("Query.profile", "query", 0.11, 0.18, "api-key readable"),
    ("Query.myPreferences", "query", 0.28, 0.27, "read path"),
    ("Mutation.logExercise", "mutation", 0.68, 1.18, "guest sync replay"),
    ("Mutation.saveHealthProfile", "mutation", 0.13, 0.94, "goal writes"),
    ("Mutation.updateProfile", "mutation", 0.09, 0.88, "profile writes"),
    ("Mutation.requestProfilePhotoUpload", "mutation", 0.05, 7.90, "HEIC rejections"),
    ("Mutation.confirmProfilePhotoUpload", "mutation", 0.04, 4.10, "HEIC rejections"),
]


def gen_error_rates() -> None:
    rows = []
    for d in days():
        mau = mau_curve(d)
        for name, kind, share, base_err, note in OPERATIONS:
            requests = int(mau * share * rng.uniform(0.86, 1.14))
            err = base_err * rng.uniform(0.82, 1.2)

            # guest-sync regression step change on logFood/logExercise
            if name.startswith("Mutation.log") and d >= GUEST_SYNC_REGRESSION:
                err *= 3.4
            # photo upload: iOS 19 raised HEIC share
            if "PhotoUpload" in name and d >= date(2026, 5, 20):
                err *= 1.9
            # single-day AppSync throttling incident (INC-2026-041)
            if d == date(2026, 7, 27) and kind == "query":
                err *= 6.2

            errors = max(0, int(requests * err / 100))
            rows.append([
                d.isoformat(), name, kind, requests, errors,
                round(errors / requests * 100, 3) if requests else 0.0, note,
            ])
    write_csv(
        "02-defect-degradation/appsync-error-rates-daily.csv",
        ["date", "operation", "operation_type", "requests", "errors", "error_rate_pct", "note"],
        rows,
    )


# ---------------------------------------------------------------------------
# 02 — defect & degradation: latency percentiles (TSV)
# ---------------------------------------------------------------------------

LATENCY_OPS = [
    ("Query.exerciseEntries", 47, 132, 0.62),      # p99 drifts up: N+1 + growing history
    ("Query.healthProfile", 28, 74, 0.00),
    ("Mutation.logExercise", 55, 149, 0.05),
    ("Mutation.requestProfilePhotoUpload", 190, 612, 0.18),
    ("ExerciseHistoryPage.weekLoad", 380, 1140, 9.40),  # client-side aggregate of 7 queries
]


def gen_latency() -> None:
    rows = []
    for d in days():
        t = (d - WINDOW_START).days
        for name, p50_base, p99_base, drift in LATENCY_OPS:
            p50 = p50_base * rng.uniform(0.93, 1.09) + drift * t * 0.18
            p99 = p99_base * rng.uniform(0.9, 1.16) + drift * t
            if d == date(2026, 7, 27):  # throttling incident
                p50 *= 2.1
                p99 *= 4.4
            p90 = p50 + (p99 - p50) * 0.42
            rows.append([
                d.isoformat(), name, round(p50, 1), round(p90, 1), round(p99, 1),
                "regression" if drift > 0.5 and t > 60 else "stable",
            ])
    write_csv(
        "02-defect-degradation/appsync-latency-percentiles.tsv",
        ["date", "operation", "p50_ms", "p90_ms", "p99_ms", "status"],
        rows,
        delimiter="\t",
    )


