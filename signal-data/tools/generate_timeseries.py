def gen_retention() -> None:
    rows = []
    for i in range(12):  # 12 weekly cohorts
        cohort_week = WINDOW_START + timedelta(days=7 * i)
        for area, curve in COHORT_AREAS.items():
            size = int(rng.uniform(0.85, 1.15) * {
                "logged_exercise_week1": 1620, "viewed_history_week1": 690,
                "repeated_same_session_week1": 1150, "browsed_discover_only": 620,
                "guest_never_signed_up": 2100, "set_exercise_goal_week1": 410,
                "corporate_program_member": 240,
            }[area])
            for week in range(len(curve)):
                if cohort_week + timedelta(days=7 * week) > WINDOW_END:
                    break
                r = curve[week] * (rng.uniform(0.95, 1.05) if week else 1.0)
                rows.append([cohort_week.isoformat(), area, size, week,
                             int(size * r), round(r * 100, 2)])
    write_csv(
        "04-usage-behavioral/cohort-retention-weekly.csv",
        ["cohort_week", "cohort_definition", "cohort_size", "week_index",
         "retained_users", "retention_pct"],
        rows,
    )


